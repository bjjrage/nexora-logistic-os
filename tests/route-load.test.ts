import test from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {Store} from '../server/db.ts';
import {setup,type Actor} from '../server/auth.ts';
import {Logistics} from '../server/domain.ts';
import {Inventory} from '../server/inventory.ts';
import {reconcileInventory} from '../server/reconciliation.ts';
import {createApp} from '../server/app.ts';
const cmd=()=>({commandId:randomUUID()});
async function fixture(t:any){
 const db=new Store(':memory:');t.after(()=>db.close());
 const credentials={organizationName:'QA load',timezone:'UTC',username:'qa-load',password:'QA-Load-2026!'};
 const identity=await setup(db,credentials),actor:Actor={id:identity.userId,orgId:identity.orgId,name:'QA',role:'ADMIN',driverId:null};
 const d=new Logistics(db),inv=new Inventory(db);
 const client=(await d.createClient(actor,{...cmd(),name:'QA client'})).id;
 await db.run('INSERT INTO client_delivery_policies VALUES(?,?,?,?)',actor.orgId,client,'NEXORA',new Date().toISOString());
 const product=(await inv.createProduct(actor,{...cmd(),clientId:client,sku:'FAN',name:'Fan QA',tracking:'QUANTITY',weightGrams:1000,volumeCm3:1000})).id;
 const location=(await inv.createLocation(actor,{...cmd(),code:'DEP',name:'Depot',kind:'STORAGE'})).id;
 await inv.receive(actor,{...cmd(),clientId:client,productId:product,locationId:location,quantity:3});
 const order=(await inv.createOrder(actor,{...cmd(),clientId:client,externalId:'LOAD-QA',orderDate:'2026-10-28',destination:'Demo',recipientName:'QA receiver',lines:[{productId:product,quantity:2}]})).id;
 const reserved=await inv.reserveOrder(actor,order,cmd());
 const driver=(await d.createDriver(actor,{...cmd(),name:'Driver QA',username:'qa-driver',password:'QA-Driver-2026!'})).id;
 const vehicle=(await d.createVehicle(actor,{...cmd(),plate:'QA-LOAD',capacityWeightGrams:10000,capacityVolumeCm3:10000,odometer:0})).id;
 const route=(await d.createRoute(actor,{...cmd(),name:'QA route',driverId:driver,vehicleId:vehicle,trackingProvider:'TRACCAR',startAt:new Date(Date.now()-60000).toISOString(),endAt:new Date(Date.now()+3600000).toISOString()})).id;
 const version=async()=>(await d.route(route,actor)).version;
 await d.assign(actor,route,{...cmd(),expectedVersion:await version(),parcelIds:reserved.parcels.map((p:any)=>p.id),pickup:false});
 return {db,d,inv,actor,order,route,vehicle,product,credentials,version,parcels:reserved.parcels};
}
test('route loading is the only physical confirmation: partial/full, retry, unload and dispatch update order and stock',async t=>{
 const f=await fixture(t),ids=f.parcels.map((p:any)=>p.id);
 assert.equal((await f.db.one('SELECT status FROM inventory_orders WHERE id=?',f.order))!.status,'RESERVED');
 await assert.rejects(f.d.ready(f.actor,f.route,{...cmd(),expectedVersion:await f.version()}),{code:'INVALID_TRANSITION'});
 const first={...cmd(),expectedVersion:await f.version(),parcelIds:[ids[0]]};
 const result=await f.d.loadSelected(f.actor,f.route,first);
 assert.deepEqual(await f.d.loadSelected(f.actor,f.route,first),result);
 assert.equal((await f.db.one('SELECT status FROM inventory_orders WHERE id=?',f.order))!.status,'PARTIALLY_LOADED');
 await assert.rejects(f.d.ready(f.actor,f.route,{...cmd(),expectedVersion:await f.version()}),{code:'INVALID_TRANSITION'});
 await f.d.loadSelected(f.actor,f.route,{...cmd(),expectedVersion:await f.version(),parcelIds:ids});
 assert.equal((await f.db.one('SELECT status FROM inventory_orders WHERE id=?',f.order))!.status,'LOADED');
 const version=await f.version();
 assert.equal((await f.d.loadSelected(f.actor,f.route,{...cmd(),expectedVersion:version,parcelIds:ids})).loaded,0);
 assert.equal(await f.version(),version);
 assert.equal(Number((await f.db.one("SELECT count(*) n FROM custody_events WHERE action='LOADED'"))!.n),2);
 await f.d.ready(f.actor,f.route,{...cmd(),expectedVersion:await f.version()});
 await f.d.unload(f.actor,f.route,{...cmd(),expectedVersion:await f.version(),parcelId:ids[0]});
 assert.equal((await f.d.route(f.route,f.actor)).state,'DRAFT');
 await assert.rejects(f.d.ready(f.actor,f.route,{...cmd(),expectedVersion:await f.version()}),{code:'INVALID_TRANSITION'});
 assert.equal((await f.db.one('SELECT status FROM inventory_orders WHERE id=?',f.order))!.status,'PARTIALLY_LOADED');
 await f.d.loadSelected(f.actor,f.route,{...cmd(),expectedVersion:await f.version(),parcelIds:[ids[0]]});
 await f.d.ready(f.actor,f.route,{...cmd(),expectedVersion:await f.version()});
 await f.d.inspect(f.actor,f.vehicle,{...cmd(),odometer:0,fuelPercent:90,items:[{label:'Observed QA',severity:'OK',note:''}]});
 await f.d.dispatch(f.actor,f.route,{...cmd(),expectedVersion:await f.version()});
 assert.equal((await f.db.one('SELECT status FROM inventory_orders WHERE id=?',f.order))!.status,'IN_TRANSIT');
 assert.equal((await reconcileInventory(f.db,f.actor)).ok,true);
});
test('selected load rejects foreign parcels, unauthorized roles, duplicates and excess capacity without partial writes',async t=>{
 const f=await fixture(t),ids=f.parcels.map((p:any)=>p.id),version=await f.version();
 const before=await f.db.all('SELECT * FROM inventory_balances');
 await assert.rejects(f.d.loadSelected(f.actor,f.route,{...cmd(),expectedVersion:version,parcelIds:[ids[0],randomUUID()]}),{code:'NOT_FOUND'});
 await assert.rejects(f.d.loadSelected({...f.actor,role:'DRIVER'},f.route,{...cmd(),expectedVersion:version,parcelIds:ids}),{code:'FORBIDDEN'});
 await assert.rejects(f.d.loadSelected(f.actor,f.route,{...cmd(),expectedVersion:version,parcelIds:[ids[0],ids[0]]}));
 await assert.rejects(f.d.loadSelected({...f.actor,orgId:randomUUID()},f.route,{...cmd(),expectedVersion:version,parcelIds:ids}),{code:'NOT_FOUND'});
 await f.db.run('UPDATE vehicles SET capacity_weight_grams=1500 WHERE id=?',f.vehicle);
 await assert.rejects(f.d.loadSelected(f.actor,f.route,{...cmd(),expectedVersion:version,parcelIds:ids}),{code:'CAPACITY_EXCEEDED'});
 assert.deepEqual(await f.db.all('SELECT * FROM inventory_balances'),before);
 assert.equal((await f.db.one('SELECT status FROM inventory_orders WHERE id=?',f.order))!.status,'RESERVED');
 assert.equal(await f.version(),version);
});
test('route selected-load HTTP persists once and rejects stale versions; no order load request required',async t=>{
 const f=await fixture(t),server=createApp(f.db).listen(0,'127.0.0.1');await new Promise<void>(resolve=>server.once('listening',resolve));
 t.after(()=>new Promise<void>(resolve=>server.close(()=>resolve())));
 const base='http://127.0.0.1:'+(server.address() as any).port;
 const login=await fetch(base+'/api/login',{method:'POST',headers:{'Content-Type':'application/json','X-Requested-With':'logistics-os'},body:JSON.stringify(f.credentials)});
 const cookie=login.headers.get('set-cookie')!.split(';')[0],version=await f.version();
 const body={...cmd(),expectedVersion:version,parcelIds:f.parcels.map((p:any)=>p.id)};
 const send=(data:any)=>fetch(base+'/api/routes/'+f.route+'/load-selected',{method:'POST',headers:{Cookie:cookie,'Content-Type':'application/json','X-Requested-With':'logistics-os'},body:JSON.stringify(data)});
 assert.equal((await send(body)).status,200);assert.equal((await send(body)).status,200);
 assert.equal((await send({...body,...cmd()})).status,409);
 assert.equal((await f.db.one('SELECT status FROM inventory_orders WHERE id=?',f.order))!.status,'LOADED');
 assert.equal((await reconcileInventory(f.db,f.actor)).ok,true);
});

test('warehouse bootstrap identifies articles and exact serials in the route',async t=>{
 const f=await fixture(t);
 const product=(await f.inv.createProduct(f.actor,{...cmd(),clientId:(await f.db.one('SELECT client_id FROM inventory_orders WHERE id=?',f.order))!.client_id,sku:'SERIAL',name:'Serialized QA',tracking:'SERIAL',weightGrams:100,volumeCm3:100})).id;
 const client=(await f.db.one('SELECT client_id FROM inventory_orders WHERE id=?',f.order))!.client_id,location=(await f.db.one('SELECT id FROM inventory_locations WHERE org_id=? LIMIT 1',f.actor.orgId))!.id;
 await f.inv.receive(f.actor,{...cmd(),clientId:client,productId:product,locationId:location,quantity:1,serials:[{serial:'SERIAL-EXACT-01'}]});
 const order=(await f.inv.createOrder(f.actor,{...cmd(),clientId:client,externalId:'SERIAL-ORDER',orderDate:'2026-10-28',destination:'Demo',recipientName:'QA',lines:[{productId:product,quantity:1}]})).id;
 const reservation=await f.inv.reserveOrder(f.actor,order,cmd());
 const bootstrap=await f.d.bootstrap({...f.actor,role:'DEPOT'});
 assert.equal(bootstrap.parcels.find((p:any)=>p.id===f.parcels[0].id)?.product?.name,'Fan QA');
 assert.equal(bootstrap.parcels.find((p:any)=>p.id===reservation.parcels[0].id)?.product?.serial,'SERIAL-EXACT-01');
});
