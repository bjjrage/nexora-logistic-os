import {test,expect} from '@playwright/test';
import {randomUUID} from 'node:crypto';
test.skip(!process.env.ROUTING_E2E,'Usar playwright.routing.config.ts para los servicios de mapas aislados.');
test('plan in Orders, locate destination, apply once and open physical loading in the same route',async({page})=>{
 const send=async(path:string,data:Record<string,unknown>)=>{const r=await page.request.post(path,{headers:{'X-Requested-With':'logistics-os'},data:{commandId:randomUUID(),...data}});expect(r.ok(),path+': '+await r.text()).toBeTruthy();return r.json();};
 await send('/api/setup',{organizationName:'Routing browser QA',timezone:'UTC',username:'qa-routing',password:'Routing-Browser-2026!'});
 const client=(await send('/api/clients',{name:'Cliente browser'})).id;
 await send('/api/clients/'+client+'/delivery-provider',{deliveryProvider:'NEXORA'});
 const vehicle=(await send('/api/vehicles',{plate:'PLAN-TEST',capacityWeightGrams:10000,capacityVolumeCm3:10000,odometer:0})).id;
 const driver=(await send('/api/drivers',{name:'Chofer browser',username:'qa-driver-routing',password:'Routing-Driver-2026!'})).id;
 const location=(await send('/api/inventory/locations',{code:'PLAN-BASE',name:'Base QA'})).id;
 const product=(await send('/api/inventory/products',{clientId:client,sku:'PLAN-SKU',name:'Ventilador QA',tracking:'QUANTITY',weightGrams:100,volumeCm3:100})).id;
 await send('/api/inventory/receipts',{clientId:client,productId:product,locationId:location,quantity:2});
 const order=(await send('/api/orders',{clientId:client,externalId:'PLAN-BROWSER',orderDate:'2026-10-29',recipientName:'Receptor browser',destination:'Direccion QA',lines:[{productId:product,quantity:2}]})).id;
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');await page.getByRole('button',{name:'Empresa y equipo',exact:true}).click();
 const depots=page.getByRole('region',{name:'Depósitos de la empresa'});
 await depots.getByLabel('Buscar ubicación').fill('J9XG+VVH, San Vicente & Aca Ver\u00e1, Lambar\u00e9');
 await depots.getByRole('button',{name:'Buscar',exact:true}).click();
 await expect(depots.locator('.leaflet-marker-icon')).toBeVisible();
 await expect(depots.getByRole('button',{name:'Guardar ubicaci\u00f3n'})).toBeEnabled();
 const searchPoint=(await(await page.request.get('/api/routing/context')).json()).points;expect(searchPoint).toHaveLength(0);
 await depots.getByRole('region',{name:'Mapa para elegir ubicaci\u00f3n'}).click({position:{x:190,y:120}});
 await page.screenshot({path:'.local/simple-picker.png',fullPage:true});
 await depots.getByRole('button',{name:'Guardar ubicaci\u00f3n'}).click();
 await expect(depots.getByText('Ubicaci\u00f3n guardada.',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Pedidos',exact:true}).click();
 await page.getByRole('button',{name:'Reservar pedido',exact:true}).click();
 const dialog=page.getByRole('dialog',{name:'Reserva y ruta'});
 await expect(dialog.locator('.routing-suggestions')).toContainText('PLAN-TEST');
 await expect(dialog.locator('.routing-suggestions')).toContainText('Chofer browser');
 await dialog.getByRole('button',{name:'Cerrar',exact:true}).click();
 await page.getByRole('button',{name:'Organizar pedidos',exact:true}).click();
 const panel=page.getByRole('region',{name:'Organizar reparto'});
 await expect(page.getByRole('navigation',{name:'Vistas de pedidos'}).getByRole('button',{name:'Organizar pedidos'})).toHaveCount(0);
 await expect(panel.locator('summary').filter({hasText:'PLAN-BASE'})).toHaveCount(0);
 await expect(panel.locator('.routing-suggestions')).toContainText('PLAN-TEST');
 await expect(panel.locator('.routing-suggestions')).toContainText('Chofer browser');
 await panel.locator('summary').filter({hasText:'Destinatarios por ubicar'}).click();
 const editor=panel.locator('article').filter({hasText:'Receptor browser'}).locator('.place-picker');
 await editor.getByRole('button',{name:'Buscar',exact:true}).click();
 await expect(editor.locator('.leaflet-marker-icon')).toBeVisible();
 await editor.getByRole('button',{name:'Guardar ubicaci\u00f3n'}).click();

 await expect(panel.getByRole('heading',{name:'Propuesta de reparto'})).toBeVisible({timeout:25000});
 await expect(panel.locator('.routing-route')).toContainText('PLAN-SKU × 2');
 await panel.getByRole('button',{name:'Confirmar reparto',exact:true}).click();
 await expect(panel.getByRole('heading',{name:'Reparto asignado'})).toBeVisible();
 const state=await(await page.request.get('/api/orders/'+order)).json();expect(state.status).toBe('RESERVED');
 const bootstrap=await(await page.request.get('/api/bootstrap')).json();
 const route=bootstrap.routes.find((r:any)=>r.vehicleId===vehicle);expect(route).toBeTruthy();
 await panel.getByRole('button',{name:/Abrir carga · Reparto/}).click();
 await expect(page.getByText('Ventilador QA',{exact:false}).first()).toBeVisible();
 expect(errors).toEqual([]);
});
