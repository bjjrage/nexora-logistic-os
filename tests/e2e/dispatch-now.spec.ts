import {test,expect} from '@playwright/test';
import {randomUUID} from 'node:crypto';

test('loaded draft dispatches now from its own screen, saves inspection there and ignores the future schedule',async({page})=>{
 const send=async(path:string,data:Record<string,unknown>)=>{const response=await page.request.post(path,{headers:{'X-Requested-With':'logistics-os'},data:{commandId:randomUUID(),...data}});expect(response.ok(),await response.text()).toBeTruthy();return response.json();};
 const session=await(await page.request.get('/api/session')).json();
 if(session.setupRequired)await send('/api/setup',{organizationName:'QA salida inmediata',timezone:'America/Asuncion',username:'qa-browser',password:'QA-Browser-Isolated-2026!'});else await send('/api/login',{username:'qa-browser',password:'QA-Browser-Isolated-2026!'});
 const suffix=randomUUID().slice(0,8),routeName='Salida ahora '+suffix;
 const client=(await send('/api/clients',{name:'Cliente salida '+suffix})).id;
 await send('/api/clients/'+client+'/delivery-provider',{deliveryProvider:'NEXORA'});
 const driver=(await send('/api/drivers',{name:'Chofer salida '+suffix,username:'salida-'+suffix,password:'QA-Departure-2026!'})).id;
 const vehicle=(await send('/api/vehicles',{plate:'NOW-'+suffix,capacityWeightGrams:10000,capacityVolumeCm3:10000,odometer:0})).id;
 const location=(await send('/api/inventory/locations',{code:'NOW-'+suffix,name:'Deposito QA'})).id;
 const product=(await send('/api/inventory/products',{clientId:client,sku:'NOW-'+suffix,name:'Ventilador QA',tracking:'QUANTITY'})).id;
 await send('/api/inventory/receipts',{clientId:client,productId:product,locationId:location,quantity:1});
 const order=(await send('/api/orders',{clientId:client,externalId:'NOW-'+suffix,orderDate:'2026-10-29',recipientName:'Receptor QA',destination:'Destino QA',lines:[{productId:product,quantity:1}]})).id;
 await send('/api/orders/'+order+'/reserve',{});
 const detail=async()=> (await(await page.request.get('/api/orders/'+order)).json());
 const parcel=(await detail()).parcels[0];
 const scheduledStart=new Date(Date.now()+86400000).toISOString(),scheduledEnd=new Date(Date.now()+93600000).toISOString();
 const route=(await send('/api/routes',{name:routeName,driverId:driver,vehicleId:vehicle,trackingProvider:'TRACCAR',startAt:scheduledStart,endAt:scheduledEnd})).id;
 const bootstrap=async()=> (await(await page.request.get('/api/bootstrap')).json());
 const routeDetail=async()=> (await bootstrap()).routes.find((item:any)=>item.id===route);
 await send('/api/routes/'+route+'/assignments',{expectedVersion:1,parcelIds:[parcel.id],pickup:false});
 await send('/api/routes/'+route+'/load-selected',{expectedVersion:(await routeDetail()).version,parcelIds:[parcel.id]});
 const readyRequests:string[]=[];
 page.on('request',request=>{if(new URL(request.url()).pathname==='/api/routes/'+route+'/ready')readyRequests.push(request.url());});
 await page.goto('/');await page.getByRole('button',{name:'Rutas',exact:true}).click();
 await page.getByRole('searchbox',{name:'Buscar ruta',exact:true}).fill(suffix);
 await page.getByRole('button',{name:new RegExp(routeName)}).click();
 const departure=page.getByRole('button',{name:'Despachar ahora',exact:true});
 await expect(departure).toBeVisible();await expect(departure).toBeEnabled();
 await page.screenshot({path:'.local/dispatch-now-loaded-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await expect(departure).toBeVisible();expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:'.local/dispatch-now-loaded-mobile.png',fullPage:true});
 await page.setViewportSize({width:1365,height:900});
 await departure.click();
 await expect(page.getByRole('alert')).toContainText('checklist');
 await expect(page.getByRole('button',{name:'Control de salida',exact:true})).toHaveAttribute('aria-pressed','true');
 expect((await routeDetail()).state).toBe('DRAFT');expect((await routeDetail()).startAt).toBe(scheduledStart);
 expect((await detail()).status).toBe('LOADED');
 await page.getByRole('spinbutton',{name:'Odómetro observado',exact:true}).fill('0');
 await page.getByRole('spinbutton',{name:'Combustible (%)',exact:true}).fill('75');
 await page.getByRole('textbox',{name:'Nombre del control',exact:true}).fill('Control físico de salida QA');
 const before=Date.now();
 await page.getByRole('button',{name:'Guardar checklist y despachar ahora',exact:true}).click();
 await expect(page.getByText('Salida de ruta registrada.',{exact:true})).toBeVisible();
 await expect(page.getByRole('button',{name:'Registrar intento en esta parada',exact:true})).toBeVisible();
 const departed=await routeDetail();expect(departed.state).toBe('IN_PROGRESS');
 expect(Date.parse(departed.startAt)).toBeGreaterThanOrEqual(before);
 expect(Date.parse(departed.startAt)).toBeLessThanOrEqual(Date.now());
 expect(Date.parse(departed.endAt)-Date.parse(departed.startAt)).toBe(7200000);
 expect((await detail()).status).toBe('IN_TRANSIT');expect(readyRequests).toEqual([]);
 expect((await(await page.request.get('/api/inventory/reconciliation')).json()).ok).toBe(true);
});
