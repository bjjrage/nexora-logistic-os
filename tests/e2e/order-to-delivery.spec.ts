import {test,expect} from '@playwright/test';
import {randomUUID} from 'node:crypto';

test('reserve → assign → route load → inspection → delivery stays in the route; order never asks for a second load',async({page})=>{
 const send=async(path:string,data:Record<string,unknown>)=>{const r=await page.request.post(path,{headers:{'X-Requested-With':'logistics-os'},data:{commandId:randomUUID(),...data}});expect(r.ok(),path+': '+await r.text()).toBeTruthy();return r.json();};
 const session=await(await page.request.get('/api/session')).json();
 if(session.setupRequired)await send('/api/setup',{organizationName:'QA flujo continuo',timezone:'America/Asuncion',username:'qa-browser',password:'QA-Browser-Isolated-2026!'});else await send('/api/login',{username:'qa-browser',password:'QA-Browser-Isolated-2026!'});
 const suffix=randomUUID().slice(0,8),routeName='Reparto continuo '+suffix;
 const client=(await send('/api/clients',{name:'Cliente continuo '+suffix})).id;
 await send('/api/clients/'+client+'/delivery-provider',{deliveryProvider:'NEXORA'});
 const driver=(await send('/api/drivers',{name:'Chofer continuo '+suffix,username:'driver-'+suffix,password:'QA-Driver-Flow-2026!'})).id;
 const vehicle=(await send('/api/vehicles',{plate:'FLOW-'+suffix,capacityWeightGrams:10000,capacityVolumeCm3:10000,odometer:0})).id;
 const loc=(await send('/api/inventory/locations',{code:'FLOW-'+suffix,name:'Deposito demo'})).id;
 const product=(await send('/api/inventory/products',{clientId:client,sku:'FLOW-'+suffix,name:'Cocina demo',tracking:'QUANTITY',weightGrams:100,volumeCm3:100})).id;
 await send('/api/inventory/receipts',{clientId:client,productId:product,locationId:loc,quantity:3});
 const order=(await send('/api/orders',{clientId:client,externalId:'FLOW-'+suffix,orderDate:'2026-10-28',recipientName:'Receptor demo',destination:'Direccion demo',lines:[{productId:product,quantity:2}]})).id;
 const route=(await send('/api/routes',{name:routeName,driverId:driver,vehicleId:vehicle,trackingProvider:'TRACCAR',startAt:new Date(Date.now()-60000).toISOString(),endAt:new Date(Date.now()+3600000).toISOString()})).id;
 const orderDetail=async()=> (await page.request.get('/api/orders/'+order)).json();
 const duplicateLoads:string[]=[];page.on('request',request=>{if(/\/api\/orders\/[^/]+\/load$/.test(new URL(request.url()).pathname))duplicateLoads.push(request.url());});
 await page.goto('/');await page.getByRole('button',{name:'Pedidos',exact:true}).click();
 await page.getByRole('article').filter({hasText:'FLOW-'+suffix}).getByRole('button',{name:'Reservar pedido',exact:true}).click();
 const dialog=page.getByRole('dialog',{name:'Reserva y ruta'});
 await dialog.getByRole('button',{name:'Reservar stock',exact:true}).click();
 await expect(dialog.getByRole('button',{name:'Confirmar carga',exact:true})).toHaveCount(0);
 await dialog.getByRole('combobox',{name:'Ruta para este pedido',exact:true}).selectOption(route);
 await dialog.getByRole('button',{name:'Asignar y abrir ruta',exact:true}).click();
 await expect(page.getByRole('heading',{name:routeName,exact:true})).toBeVisible();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await page.getByRole('button',{name:'Confirmar plan',exact:true}).click();
 await expect(page.getByText('Plan confirmado',{exact:true})).toBeVisible();
 await expect(page.getByRole('button',{name:'Despachar',exact:true})).toBeDisabled();
 expect((await orderDetail()).status).toBe('RESERVED');
 const load=page.getByRole('region',{name:'Carga del vehículo',exact:true});
 await load.getByRole('checkbox',{name:/Cocina demo · unidad 1/}).check();
 await load.getByRole('button',{name:'Confirmar carga',exact:true}).click();
 await expect(load).toContainText('Cargados 1 de 2 bultos.');
 expect((await orderDetail()).status).toBe('PARTIALLY_LOADED');
 await expect(load.getByRole('checkbox',{name:/Cocina demo · unidad 1/})).toBeDisabled();
 await load.getByRole('checkbox',{name:/Cocina demo · unidad 2/}).check();
 await load.getByRole('button',{name:'Confirmar carga',exact:true}).click();
 await expect(load).toContainText('Carga completa. No tenés que confirmar nada en Pedidos.');
 expect((await orderDetail()).status).toBe('LOADED');
 await page.screenshot({path:'.local/route-single-load.png',fullPage:true});
 await page.getByRole('button',{name:'Control de salida',exact:true}).click();
 await page.getByRole('spinbutton',{name:'Odómetro observado',exact:true}).fill('0');
 await page.getByRole('spinbutton',{name:'Combustible (%)',exact:true}).fill('90');
 await page.getByRole('textbox',{name:'Nombre del control',exact:true}).fill('Control observado demo');
 await page.getByRole('button',{name:'Guardar checklist',exact:true}).click();
 await expect(page.getByText('Checklist de salida guardado.',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Despachar',exact:true}).click();
 await expect(page.getByRole('button',{name:'Registrar intento en esta parada',exact:true})).toBeVisible();
 expect((await orderDetail()).status).toBe('IN_TRANSIT');
 await page.getByRole('button',{name:'Registrar intento en esta parada',exact:true}).click();
 for(const choice of await page.getByRole('checkbox',{name:'Entregado',exact:true}).all())await choice.check();
 await page.getByRole('textbox',{name:'Nombre de quien recibe',exact:true}).fill('Receptor ficticio demo');
 const detail=await orderDetail();
 for(const parcel of detail.parcels){
  await page.getByRole('combobox',{name:'Bulto al que pertenece la foto',exact:true}).selectOption(parcel.id);
  await page.getByLabel('Agregar evidencia fotográfica',{exact:true}).setInputFiles({name:'demo.png',mimeType:'image/png',buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aCioAAAAASUVORK5CYII=','base64')});
 }
 await expect(page.getByRole('link',{name:'Ver foto 2',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Guardar resultado',exact:true}).click();
 await expect.poll(async()=> (await orderDetail()).status).toBe('DELIVERED');
 await page.getByRole('button',{name:'Cerrar ruta',exact:true}).click();
 await expect.poll(async()=> (await(await page.request.get('/api/bootstrap')).json()).routes.find((r:any)=>r.id===route).state).toBe('OPERATIONALLY_CLOSED');
 await page.getByRole('button',{name:'Pedidos',exact:true}).click();
 const card=page.getByRole('article').filter({hasText:'FLOW-'+suffix});
 await expect(card).toContainText('Entregado');await expect(card.getByRole('button',{name:/cargar|Confirmar carga/i})).toHaveCount(0);
 expect(duplicateLoads).toEqual([]);
 expect((await(await page.request.get('/api/inventory/reconciliation')).json()).ok).toBe(true);
});
