import {test,expect} from '@playwright/test';
import {randomUUID} from 'node:crypto';

test('orders filter all clients on the server, reset pagination and import into the chosen client',async({page})=>{
 const send=async(path:string,data:Record<string,unknown>)=>{const r=await page.request.post(path,{headers:{'X-Requested-With':'logistics-os'},data:{commandId:randomUUID(),...data}});expect(r.ok(),path+': '+await r.text()).toBeTruthy();return r.json();};
 const session=await(await page.request.get('/api/session')).json();
 if(session.setupRequired)await send('/api/setup',{organizationName:'QA clientes pedidos',timezone:'America/Asuncion',username:'qa-browser',password:'QA-Browser-Isolated-2026!'});else await send('/api/login',{username:'qa-browser',password:'QA-Browser-Isolated-2026!'});
 const suffix=randomUUID().slice(0,8);
 const a=(await send('/api/clients',{name:'Pelmar QA '+suffix})).id;
 const b=(await send('/api/clients',{name:'Bristol QA '+suffix})).id;
 const empty=(await send('/api/clients',{name:'Sin pedidos QA '+suffix})).id;
 const product=async(clientId:string)=> (await send('/api/inventory/products',{clientId,sku:'SKU-'+suffix,name:'Producto QA',tracking:'QUANTITY'})).id;
 const pa=await product(a),pb=await product(b),pc=await product(empty);
 const location=(await send('/api/inventory/locations',{code:'QA-'+suffix,name:'Deposito QA'})).id;
 await send('/api/inventory/receipts',{clientId:empty,productId:pc,locationId:location,quantity:5});
 const order=(clientId:string,productId:string,externalId:string)=>({clientId,externalId,orderDate:'2026-10-28',recipientName:'Destinatario QA',destination:'Destino QA',lines:[{productId,quantity:1}]});
 await send('/api/orders/import',{clientId:a,orders:Array.from({length:22},(_,i)=>order(a,pa,'PEL-'+suffix+'-'+i))});
 await send('/api/orders',order(b,pb,'BRI-'+suffix));
 await page.goto('/');await page.getByRole('button',{name:'Pedidos',exact:true}).click();
 const filter=page.getByRole('combobox',{name:'Cliente de los pedidos',exact:true});
 await expect(filter).toHaveValue('');
 for(const [id,name] of [['','Todos los clientes'],[a,'Pelmar QA '+suffix],[b,'Bristol QA '+suffix],[empty,'Sin pedidos QA '+suffix]])await expect(filter.locator('option').filter({hasText:name})).toHaveAttribute('value',id);
 await filter.selectOption(a);await expect(page.getByRole('article')).toHaveCount(20);
 await page.getByRole('button',{name:'Siguiente',exact:true}).click();
 await expect(page.getByText('Página 2 de 2',{exact:true})).toBeVisible();
 const query=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/orders'&&new URL(r.url()).searchParams.get('clientId')===b);
 await filter.selectOption(b);
 const response=await query;expect(new URL(response.url()).searchParams.get('offset')).toBe('0');
 expect((await response.json()).total).toBe(1);
 await expect(page.getByRole('article')).toHaveCount(1);
 await expect(page.getByRole('article')).toContainText('BRI-'+suffix);
 await page.screenshot({path:'.local/orders-client-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:'.local/orders-client-mobile.png',fullPage:true});
 await page.setViewportSize({width:1365,height:900});
 await filter.selectOption(a);await expect(page.getByRole('article')).toHaveCount(20);
 await page.getByRole('button',{name:'Siguiente',exact:true}).click();await expect(page.getByRole('article')).toHaveCount(2);
 await filter.selectOption(empty);
 await expect(page.getByRole('heading',{name:'No hay pedidos para Sin pedidos QA '+suffix,exact:true})).toBeVisible();
 await expect(page.getByRole('article')).toHaveCount(0);
 await page.getByRole('button',{name:'Importar pedidos',exact:true}).click();
 await expect(page.getByRole('combobox',{name:'Cliente',exact:true})).toHaveValue(empty);
 await page.getByText('O pegar contenido CSV',{exact:true}).click();
 await page.getByRole('textbox',{name:/^Contenido CSV/}).fill('externalId,date,destination,recipientName,sku,quantity\nIMP-'+suffix+',2026-10-28,Destino QA,Destinatario QA,SKU-'+suffix+',1');
 await page.getByRole('button',{name:'Validar pedidos',exact:true}).click();
 await expect(page.getByText('Validación completada',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Importar validados',exact:true}).click();
 await expect(page.getByText('1 pedidos importados.',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Pedidos',exact:true}).last().click();
 await expect(filter).toHaveValue(empty);
 await expect(page.getByRole('article')).toHaveCount(1);
 await expect(page.getByRole('article')).toContainText('IMP-'+suffix);
 expect((await(await page.request.get('/api/orders?clientId='+a)).json()).total).toBe(22);
 expect((await(await page.request.get('/api/orders?clientId='+b)).json()).total).toBe(1);
 await filter.selectOption('');await expect(page.getByRole('article')).toHaveCount(20);
 await page.getByRole('button',{name:'Importar pedido',exact:true}).click();
 await expect(page.getByRole('combobox',{name:'Cliente',exact:true})).toHaveValue('');
});
