  const store=new Store(':memory:');t.after(()=>store.close());
  const ids=await setup(store,{organizationName:'QA GPS',timezone:'America/Asuncion',username:'gps-'+randomUUID(),password:'GPS-Testing-2026!'});
  const actor:Actor={id:ids.userId,orgId:ids.orgId,name:'QA',role:'ADMIN',driverId:null},domain=new Logistics(store);
  const driver=await domain.createDriver(actor,{...command(),name:'Chofer',username:'driver-'+randomUUID(),password:'GPS-Driver-2026!'});
  const vehicle=await domain.createVehicle(actor,{...command(),plate:'GPS-1',capacityWeightGrams:10000,capacityVolumeCm3:10000,odometer:0});
  const route=await domain.createRoute(actor,{...command(),name:'Ruta propia',driverId:driver.id,vehicleId:vehicle.id,startAt:new Date(time-3600000).toISOString(),endAt:new Date(time+3600000).toISOString()});
  const tracking=new TraccarTracking(store,{},fetch,()=>time);
  await store.run('INSERT INTO traccar_devices VALUES(?,?,?,?,?)','123',actor.orgId,'NX-'+randomUUID(),'Teléfono QA',new Date(time-1000).toISOString());
  await tracking.bind(actor,vehicle.id,{...command(),deviceId:'123'});
